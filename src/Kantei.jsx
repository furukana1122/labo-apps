// 干支番号（1〜60）を返す関数
function getKanshiNumber(kan, shi) {
  const kanIdx = ["甲","乙","丙","丁","戊","己","庚","辛","壬","癸"].indexOf(kan);
  const shiIdx = ["子","丑","寅","卯","辰","巳","午","未","申","酉","戌","亥"].indexOf(shi);
  return ((kanIdx * 6 - shiIdx * 5) % 60 + 60) % 60 + 1;
}



